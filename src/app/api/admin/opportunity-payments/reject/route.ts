import { NextRequest, NextResponse } from 'next/server';
import { sequelize, connectDB } from '@/lib/sequelize';
import { QueryTypes } from 'sequelize';
import { requireAuth, isAuthError } from '@/lib/apiAuth';
import { isCeo } from '@/lib/roleChecks';
import { logAudit } from '@/lib/auditLog';
import { notifyUser } from '@/lib/notify';
import { captureError } from '@/lib/errorTracking';

let dbInitialized = false;
const ensureDB = async () => { if (!dbInitialized) { await connectDB(); dbInitialized = true; } };

// CEO-only undo of a payment that was approved by mistake. Approval generates
// the agreement (and unlocks the receipt), so rejecting here reverses all of
// it atomically: the payment is marked rejected (receipt no longer viewable),
// the agreement and its contract-register row are deleted, the paid amount is
// put back on the contract/lead, the finance gate is reset, and the lead's
// opportunity flow is rewound to the first step so the counselor restarts it.
export async function POST(request: NextRequest) {
  try {
    const auth = requireAuth(request);
    if (isAuthError(auth)) return auth;
    if (!isCeo(auth)) {
      return NextResponse.json({ error: 'Only the CEO can reject an approved payment.' }, { status: 403 });
    }

    await ensureDB();
    const { paymentId, reason } = await request.json();
    if (!paymentId) return NextResponse.json({ error: 'paymentId is required' }, { status: 400 });
    if (!String(reason || '').trim()) return NextResponse.json({ error: 'A reason is required.' }, { status: 400 });

    const [payment] = await sequelize.query<{
      opportunityId: number; leadId: number | null; clientName: string | null; paidAmount: number;
      accountantStatus: string | null; assignedTo: number | null; leadAssignTo: number | null; formalClientId: number | null;
    }>(
      `SELECT p.opportunityId, o.leadId, p.clientName, COALESCE(p.paidAmount,0) AS paidAmount,
              COALESCE(p.accountantStatus,'pending') AS accountantStatus,
              o.assignedTo, l.assignTo AS leadAssignTo, w.formal_client_id AS formalClientId
       FROM crm_opportunity_payments p
       LEFT JOIN crm_opportunities o ON o.id = p.opportunityId
       LEFT JOIN crm_forum_leads l ON l.id = o.leadId
       LEFT JOIN crm_opportunity_workflow_reviews w ON w.opportunity_id = p.opportunityId
       WHERE p.id = :paymentId LIMIT 1`,
      { replacements: { paymentId }, type: QueryTypes.SELECT }
    );
    if (!payment) return NextResponse.json({ error: 'Payment not found.' }, { status: 404 });
    if (payment.accountantStatus === 'rejected') {
      return NextResponse.json({ error: 'This payment is already rejected.' }, { status: 409 });
    }
    if (payment.formalClientId) {
      return NextResponse.json({ error: 'Compliance has already activated this case, so the payment can no longer be rejected from here.' }, { status: 409 });
    }

    const note = `Rejected by CEO: ${String(reason).trim()}`;
    await sequelize.transaction(async (t) => {
      await sequelize.query(
        `UPDATE crm_opportunity_payments
         SET accountantStatus = 'rejected', accountantRemarks = :note, accountantId = :uid,
             accountantVerifiedAt = NOW(), updatedAt = NOW()
         WHERE id = :paymentId`,
        { replacements: { note, uid: auth.id || null, paymentId }, type: QueryTypes.UPDATE, transaction: t }
      );

      // The paid amount was added to the contract/lead when recorded; put it
      // back, exactly as an Accounts rejection does.
      if (Number(payment.paidAmount) > 0) {
        await sequelize.query(
          `UPDATE crm_contracts
           SET paid_yet = GREATEST(paid_yet - :amount, 0),
               pay_balance = GREATEST(pay_total - discount - paid_yet, 0), updated_at = NOW()
           WHERE opportunity_id = :opportunityId AND is_deleted = 0`,
          { replacements: { amount: Number(payment.paidAmount), opportunityId: payment.opportunityId }, type: QueryTypes.UPDATE, transaction: t }
        );
        if (payment.leadId) {
          await sequelize.query(
            `UPDATE crm_forum_leads
             SET paidYet = GREATEST(COALESCE(paidYet, 0) - :amount, 0),
                 payBalance = GREATEST(payTotal - paidYet, 0), demandAmt = payBalance
             WHERE id = :leadId AND opportunity_id = :opportunityId`,
            { replacements: { amount: Number(payment.paidAmount), leadId: payment.leadId, opportunityId: payment.opportunityId }, type: QueryTypes.UPDATE, transaction: t }
          );
        }
      }

      // Delete the agreement(s) generated by the approval.
      const agreements = await sequelize.query<{ agreementNumber: string }>(
        `SELECT agreementNumber FROM crm_opportunity_agreements WHERE opportunityId = :oppId AND is_deleted = 0`,
        { replacements: { oppId: payment.opportunityId }, type: QueryTypes.SELECT, transaction: t }
      );
      await sequelize.query(
        `UPDATE crm_opportunity_agreements SET is_deleted = 1, deletedAt = NOW(), deletedBy = :uid, updatedAt = NOW()
         WHERE opportunityId = :oppId AND is_deleted = 0`,
        { replacements: { oppId: payment.opportunityId, uid: auth.id || null }, type: QueryTypes.UPDATE, transaction: t }
      );
      if (payment.leadId) {
        for (const a of agreements) {
          await sequelize.query(
            `DELETE FROM crm_forum_leads_contracts WHERE leadId = :leadId AND contract = :file`,
            { replacements: { leadId: payment.leadId, file: `${a.agreementNumber}.pdf` }, type: QueryTypes.DELETE, transaction: t }
          );
        }
      }

      // Reset the finance/compliance gates.
      await sequelize.query(
        `UPDATE crm_opportunity_workflow_reviews
         SET finance_status = 'pending', compliance_status = 'pending', workflow_status = 'opportunity_created',
             finance_reviewed_by = :uid, finance_reviewed_at = NOW(), updated_at = NOW()
         WHERE opportunity_id = :oppId`,
        { replacements: { uid: auth.id || null, oppId: payment.opportunityId }, type: QueryTypes.UPDATE, transaction: t }
      );

      // Rewind the counselor's flow to step 1 (the wizard resumes from this).
      if (payment.leadId) {
        await sequelize.query(
          `UPDATE crm_forum_leads SET opportunity_stage = 'prospect' WHERE id = :leadId`,
          { replacements: { leadId: payment.leadId }, type: QueryTypes.UPDATE, transaction: t }
        );
      }
    });

    await logAudit({
      entityType: 'opportunity_payment',
      entityId: paymentId,
      action: 'payment_rejected_by_ceo',
      summary: `Payment #${paymentId} rejected by CEO; agreement/receipt removed, flow reset. ${note}`,
      actorId: auth.id ?? null,
      actorRole: auth.roleName || auth.type || null,
      after: { status: 'rejected', reason },
    });

    const counselorId = payment.assignedTo || payment.leadAssignTo;
    if (counselorId) {
      await notifyUser({
        userId: counselorId,
        type: 'payment_verification',
        title: 'Payment rejected by CEO',
        message: `The CEO rejected the payment for ${payment.clientName || `opportunity #${payment.opportunityId}`}. Reason: ${String(reason).trim()}. Please restart the opportunity flow from the first step.`,
        priority: 'high',
        link: payment.leadId ? `/admin/leads/${payment.leadId}/edit` : undefined,
        relatedId: payment.leadId ?? undefined,
        relatedType: payment.leadId ? 'lead' : undefined,
      });
    }

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Error rejecting payment:', error);
    captureError(error, { route: 'POST /api/admin/opportunity-payments/reject' });
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
}
